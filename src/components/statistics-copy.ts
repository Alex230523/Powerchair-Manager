/** Fills {name} fields. */
export const fill = (s: string, v: Record<string, string | number>) => s.replace(/\{(\w+)\}/g, (m, k: string) => (k in v ? String(v[k]) : m));
/** « 1re place », « 2e place », « 1st place »… or « Distinction ». */
export function placeLabel(t: Copy["awards"], place: number | null, locale: Locale) {
  if (place === null) return t.distinction;
  if (place === 1) return t.first;
  if (locale === "en") return `${place}${place % 10 === 2 && place % 100 !== 12 ? "nd" : place % 10 === 3 && place % 100 !== 13 ? "rd" : place % 10 === 1 && place % 100 !== 11 ? "st" : "th"} place`;
  return fill(t.nth, { n: place });
}
