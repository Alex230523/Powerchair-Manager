/**
 * Audit 26: the access matrix, source of docs/MATRICE-DROITS.md
 * (npm run audit:access writes it). Every API route and every page is
 * listed: a new one cannot be added without deciding who reaches it
 * (tests/access-matrix.test.ts). For each read (GET) and each role, the HTTP
 * status the real server must answer (tests/audit/access.spec.ts): 200
 * access, 401 sign-in needed, 403 refused, 404 not found or not one's own,
 * 400 a request this test cannot fill in (a missing parameter). A write
 * (POST) with an empty body is refused for everyone.
 */
export const matrixRoles = ["anonymous", "president", "coach", "player", "parent", "federation", "referee", "federation_worker", "president_b", "federation_b"] as const;
export type MatrixRole = (typeof matrixRoles)[number];
type Statuses = Partial<Record<MatrixRole, number>>;
